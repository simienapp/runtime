//! Write a schema as `schema.ts`, and as the generated TypeScript in `simien/_generated`.
//!
//! `schema_ts` is what `simien dev` writes when the database changes underneath it, so its output
//! parses back to the same schema (tested below).

use crate::model::{Field, ID, SOURCE, Schema, TARGET, Type};

pub const IMPORT: &str = "@simien/client/schema";

fn validator(field: &Field) -> String {
    if field.optional {
        format!("v.optional({})", field.ty.validator())
    } else {
        field.ty.validator().to_string()
    }
}

fn object(fields: &[Field]) -> String {
    if fields.is_empty() {
        return "{}".to_string();
    }
    let entries: Vec<String> = fields.iter().map(|f| format!("    {}: {},", f.name, validator(f))).collect();
    format!("{{\n{}\n  }}", entries.join("\n"))
}

pub fn schema_ts(schema: &Schema) -> String {
    let mut out = format!("import {{ defineEdge, defineSchema, defineTable, v }} from \"{IMPORT}\"\n\nexport default defineSchema({{\n");
    for table in &schema.tables {
        out.push_str(&format!("  {}: defineTable({}),\n", table.name, object(&table.fields)));
    }
    for edge in &schema.edges {
        let fields = if edge.fields.is_empty() {
            String::new()
        } else {
            format!(", {}", object(&edge.fields))
        };
        out.push_str(&format!(
            "  {}: defineEdge(\"{}\", \"{}\"{fields}),\n",
            edge.name, edge.from, edge.to
        ));
    }
    out.push_str("})\n");
    out
}

/// `users` → `Users`, `ze_liked_by` → `ZeLikedBy`.
fn pascal(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn member(field: &Field) -> String {
    if field.optional {
        format!("  {}?: {} | null", field.name, field.ty.typescript())
    } else {
        format!("  {}: {}", field.name, field.ty.typescript())
    }
}

fn interface(name: &str, fixed: &[String], fields: &[Field]) -> String {
    let mut lines: Vec<String> = fixed.to_vec();
    lines.extend(fields.iter().map(member));
    format!("export interface {name} {{\n{}\n}}\n", lines.join("\n"))
}

fn metadata_type(ty: Type) -> &'static str {
    match ty {
        Type::Int => "int",
        Type::Float => "float",
        Type::Bool => "boolean",
        Type::String => "string",
    }
}

fn metadata_fields(fields: &[Field]) -> String {
    let entries: Vec<String> = fields
        .iter()
        .map(|f| format!("{}: {{ type: \"{}\", optional: {} }}", f.name, metadata_type(f.ty), f.optional))
        .collect();
    format!("{{ {} }}", entries.join(", "))
}

/// `simien/_generated/dataModel.ts`: a document type per table and edge, the insert shapes, and
/// the schema itself as a constant for the client to validate against.
pub fn data_model(schema: &Schema) -> String {
    let mut out = String::from(
        "// Generated by simien from simien/schema.ts. Do not edit: `simien dev` rewrites it.\n\n/** A row id: the `_id` Postgres assigns. */\nexport type Id<Table extends string> = number & { readonly __table?: Table }\n\n",
    );
    for table in &schema.tables {
        let name = pascal(&table.name);
        out.push_str(&interface(&name, &[format!("  {ID}: Id<\"{}\">", table.name)], &table.fields));
        out.push('\n');
    }
    for edge in &schema.edges {
        let name = pascal(&edge.name);
        out.push_str(&interface(
            &name,
            &[
                format!("  {SOURCE}: Id<\"{}\">", edge.from),
                format!("  {TARGET}: Id<\"{}\">", edge.to),
            ],
            &edge.fields,
        ));
        out.push('\n');
    }
    out.push_str("export interface DataModel {\n  tables: {\n");
    for table in &schema.tables {
        let name = pascal(&table.name);
        out.push_str(&format!("    {}: {{ doc: {name}; insert: Omit<{name}, \"{ID}\"> }}\n", table.name));
    }
    out.push_str("  }\n  edges: {\n");
    for edge in &schema.edges {
        let name = pascal(&edge.name);
        out.push_str(&format!(
            "    {}: {{ from: \"{}\"; to: \"{}\"; doc: {name}; props: Omit<{name}, \"{SOURCE}\" | \"{TARGET}\"> }}\n",
            edge.name, edge.from, edge.to
        ));
    }
    out.push_str("  }\n}\n\nexport const schema = {\n  tables: {\n");
    for table in &schema.tables {
        out.push_str(&format!("    {}: {},\n", table.name, metadata_fields(&table.fields)));
    }
    out.push_str("  },\n  edges: {\n");
    for edge in &schema.edges {
        out.push_str(&format!(
            "    {}: {{ from: \"{}\", to: \"{}\", fields: {} }},\n",
            edge.name,
            edge.from,
            edge.to,
            metadata_fields(&edge.fields)
        ));
    }
    out.push_str("  },\n} as const\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::parse;

    const SOURCE_TS: &str = r#"export default defineSchema({
  users: defineTable({ name: v.string(), email: v.optional(v.string()) }),
  movies: defineTable({}),
  liked: defineEdge("users", "movies", { stars: v.optional(v.int()), at: v.float() }),
  knows: defineEdge("users", "users"),
})"#;

    #[test]
    fn written_schema_reads_back_the_same() {
        let schema = parse(SOURCE_TS).unwrap();
        let written = schema_ts(&schema);
        assert_eq!(parse(&written).unwrap(), schema, "{written}");
        assert!(written.starts_with("import { defineEdge, defineSchema, defineTable, v }"));
    }

    #[test]
    fn data_model_has_types_and_metadata() {
        let model = data_model(&parse(SOURCE_TS).unwrap());
        assert!(
            model.contains("export interface Users {\n  _id: Id<\"users\">\n  name: string\n  email?: string | null\n}"),
            "{model}"
        );
        assert!(
            model.contains("export interface Liked {\n  source: Id<\"users\">\n  target: Id<\"movies\">"),
            "{model}"
        );
        assert!(model.contains("users: { doc: Users; insert: Omit<Users, \"_id\"> }"));
        assert!(model.contains("liked: { from: \"users\", to: \"movies\", fields: { stars: { type: \"int\", optional: true }, at: { type: \"float\", optional: false } } },"), "{model}");
    }
}
